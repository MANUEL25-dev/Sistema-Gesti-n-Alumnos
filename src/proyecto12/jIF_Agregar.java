    public int Verificar(String NC) {
        String sql = "SELECT COUNT(*) FROM datosgenerales WHERE NC = ?";
        try (
                Connection cnx = new ConectarBD().conexion(); PreparedStatement st = cnx.prepareStatement(sql);) {
            st.setString(1, NC);
            try (ResultSet rs = st.executeQuery()) {
                if (rs.next()) {
                    return rs.getInt(1);
                }
            }
        } catch (SQLException ex) {
            Logger.getLogger(jIF_Agregar.class.getName()).log(Level.SEVERE, null, ex);
        }
        return 0;
    }


   

