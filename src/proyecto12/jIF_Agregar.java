    private void jB_AgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jB_AgregarActionPerformed

        if (jTF_NC.getText().equals("") || jTF_Nom.getText().equals("") || jTF_Dom.getText().equals("")
                || jTF_Tel.getText().equals("") || jTF_email.getText().equals("") || jC_edad.getSelectedItem().equals("")
                || jR_Sexo.getSelectedItem().equals("")){
            JOptionPane.showMessageDialog(null, "No debe haber campos en blanco");
        } else {
            int existe=Verificar(jTF_NC.getText().trim());
            if (existe>0) {
                JOptionPane.showMessageDialog(null, "El número de control ya existe...Ingresa uno nuevo");
            } else {
                Connection cnx;
                ConectarBD conectar = new ConectarBD();
                cnx = conectar.conexion();
                try {
                    PreparedStatement st = cnx.prepareStatement("INSERT INTO datosgenerales(id, NC, Nom,Dom, Tel, email, edad,sexo) VALUES (null,?, ?, ?, ?, ?, ?,?)");
                    st.setString(1, jTF_NC.getText());
                    st.setString(2, jTF_Nom.getText());
                    st.setString(3, jTF_Dom.getText());
                    st.setString(4, jTF_Tel.getText());
                    st.setString(5, jTF_email.getText());
                    st.setString(6, (String) jC_edad.getSelectedItem());
                    st.setString(7, (String) jR_Sexo.getSelectedItem());
                    st.executeUpdate();
                } catch (SQLException v) {
                    System.out.println(v.getMessage());
                }
                JOptionPane.showMessageDialog(null, "Registro Insertado Con exito");
                this.dispose();
            }    
        }
    }//GEN-LAST:event_jB_AgregarActionPerformed

