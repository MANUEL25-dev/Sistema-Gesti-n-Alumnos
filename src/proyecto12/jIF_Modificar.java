    public void Mostrar(String jTF_NC) {
        try {
            DefaultTableModel modelo = new DefaultTableModel();
            modelo.addColumn("Id");
            modelo.addColumn("NC");
            modelo.addColumn("Nombre");
            modelo.addColumn("Dom");
            modelo.addColumn("Tel");
            modelo.addColumn("Email");
            modelo.addColumn("Edad");
            modelo.addColumn("Sexo");
            Tabla.setModel(modelo);
            String sql = "";
            if (jTF_NC.equals("")) {
                sql = "Select*from datosgenerales";
            } else {
                sql = "Select*from datosgenerales where NC like'%" + jTF_NC + "%'";
            }
            String datosgenerales[] = new String[8];
            Statement set;
            Connection cnx;
            ConectarBD conectar = new ConectarBD();
            cnx = conectar.conexion();
            set = cnx.createStatement();
            ResultSet resul = set.executeQuery(sql);
            while (resul.next()) {
                datosgenerales[0] = resul.getString(1);
                datosgenerales[1] = resul.getString(2);
                datosgenerales[2] = resul.getString(3);
                datosgenerales[3] = resul.getString(4);
                datosgenerales[4] = resul.getString(5);
                datosgenerales[5] = resul.getString(6);
                datosgenerales[6] = resul.getString(7);
                datosgenerales[7] = resul.getString(8);
                modelo.addRow(datosgenerales);
            }
            Tabla.setModel(modelo);
        } catch (SQLException ex) {
            Logger.getLogger(jIF_Buscar.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    


