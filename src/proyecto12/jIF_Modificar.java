    private void jB_ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jB_ModificarActionPerformed
        if (jTF_NC.getText().trim().isEmpty()
                || jTF_Nom.getText().trim().isEmpty()
                || jTF_Dom.getText().trim().isEmpty()
                || jTF_Tel.getText().trim().isEmpty()
                || jTF_email.getText().trim().isEmpty()
                || jC_edad.getSelectedItem() == null
                || jR_Sexo.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(null, "No debe haber campos en blanco");
        } else {
            Connection cnx;
            ConectarBD conectar = new ConectarBD();
            cnx = conectar.conexion();
            try {
                PreparedStatement st = cnx.prepareStatement(
                        "UPDATE datosgenerales SET Nom=?, Dom=?, Tel=?, email=?, edad=?, sexo=? WHERE NC=?"
                );
                st.setString(1, jTF_Nom.getText().trim());
                st.setString(2, jTF_Dom.getText().trim());
                st.setString(3, jTF_Tel.getText().trim());
                st.setString(4, jTF_email.getText().trim());
                st.setString(5, jC_edad.getSelectedItem().toString());
                st.setString(6, jR_Sexo.getSelectedItem().toString());
                
                st.setString(7, jTF_NC.getText().trim());

                int rowsAffected = st.executeUpdate();

                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(null, "Registro modificado con éxito");
                    Mostrar("");
                } else {
                    JOptionPane.showMessageDialog(null, "No se encontró un registro con ese NC");
                }
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "Error al modificar: " + e.getMessage());
            }
            this.dispose();
        } 
    }//GEN-LAST:event_jB_ModificarActionPerformed

